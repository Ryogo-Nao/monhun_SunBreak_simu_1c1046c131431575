// 正規化: 全角半角統一・小文字化・ひらがな→カタカナ・記号と空白を除去
export function norm(s) {
  return String(s || "")
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60))
    .replace(/[\s【】\[\]「」()（）・,、。.\-_〜~]/g, "");
}

// 文字が順番どおりに含まれているか（飛び飛びの一致）
function subseq(hay, needle) {
  let i = 0;
  for (const ch of hay) {
    if (ch === needle[i]) i++;
    if (i === needle.length) return true;
  }
  return needle.length === 0;
}

const cache = new Map();
function keys(text) {
  let k = cache.get(text);
  if (!k) {
    const n = norm(text);
    k = [n];
    const y = SKILL_YOMI[text];
    if (y) k.push(norm(y));
    cache.set(text, k);
  }
  return k;
}

// 検索語（空白区切りで AND）が text に部分一致するか
// fuzzy: 漢字/かなが飛び飛びでも順番どおりなら一致（2文字以上の語のみ）
export function match(text, query, fuzzy = true) {
  const terms = String(query || "").split(/[\s　]+/).map(norm).filter(Boolean);
  if (!terms.length) return true;
  const ks = keys(text);
  return terms.every((t) => ks.some((k) => k.includes(t) || (fuzzy && t.length >= 2 && subseq(k, t))));
}

// 一致度（並び替え用）: 0=完全一致 1=前方一致 2=部分一致 3=飛び飛び 9=不一致
export function score(text, query) {
  const t = norm(query);
  if (!t) return 0;
  let best = 9;
  for (const k of keys(text)) {
    if (k === t) best = Math.min(best, 0);
    else if (k.startsWith(t)) best = Math.min(best, 1);
    else if (k.includes(t)) best = Math.min(best, 2);
    else if (t.length >= 2 && subseq(k, t)) best = Math.min(best, 3);
  }
  return best;
}

// いずれかのテキスト（スキル名の配列など）に一致するか。各検索語はどれか1つに一致すればよい
export function matchAny(texts, query, fuzzy = true) {
  const terms = String(query || "").split(/[\s　]+/).filter((t) => norm(t));
  if (!terms.length) return true;
  return terms.every((t) => texts.some((x) => x && match(x, t, fuzzy)));
}
